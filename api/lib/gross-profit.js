// Валовая прибыль (из 1С) — реальная себестоимость, совпадающая с отчётом
// Маши «Валовая прибыль».
//
// Источник себестоимости: РегистрНакопления.УчётЗатрат, операция «Списание
// партий в производство», ВидДвижения = Расход — стоимость материалов (мука,
// сахар, начинки и т.д.), списанных в производство. Это и есть себестоимость в
// её отчёте: маржа = выручка − материалы (производство централизованное,
// производство ≈ продажи). Проверено 08.06.2026: маржа 73.8–74.8% по месяцам
// ≈ отчётные 74.6%.
//
// Почему не другие источники (проверено): ПартииТоваровНаСкладах — пуст по
// СтоимостьРасход; ПродажиСебестоимость/тип цен СебестоимостьМПЗ — заглушки
// 9.99e12 у произведённых товаров; РАУЗ-операция «Реализация» = ~91-112К/мес
// (производственный COGS туда не разносится); бухсчёт 90.02 — розница почти не
// отражается. Детали — reference_upp_cost_sources в памяти.
//
// КодОперации — перечисление, фильтровать `= "строка"` нельзя (несовместимые
// типы), поэтому группируем по операции и отбираем «Списание партий в
// производство» в Node по представлению.

const upp = require('./upp-client');
const cache = upp.makeCache(6 * 60 * 60 * 1000, 'gross-profit'); // 6ч, диск-персистентный

function bounds(period) {
  const [y, m] = period.split('-').map(Number);
  const next = m === 12 ? [y + 1, 1] : [y, m + 1];
  return { y, m, ny: next[0], nm: next[1] };
}

async function computeCogs(period) {
  const b = bounds(period);
  // Тяжёлый запрос (УчётЗатрат ~250к строк/мес, агрегируется на сервере 1С ~110с).
  // Кэшируется на 6ч, так что live-запрос только при холодном кэше.
  const q = 'ВЫБРАТЬ З.КодОперации КАК Оп, З.ВидДвижения КАК Вид, СУММА(З.Стоимость) КАК Сумма'
    + ' ИЗ РегистрНакопления.УчетЗатрат КАК З'
    + ` ГДЕ З.Период >= ДАТАВРЕМЯ(${b.y},${b.m},1) И З.Период < ДАТАВРЕМЯ(${b.ny},${b.nm},1)`
    + ' СГРУППИРОВАТЬ ПО З.КодОперации, З.ВидДвижения';
  const r = await upp.callQuery(q, { timeoutMs: 150000 });
  const rows = (r && r.rows) || [];
  const cogs = rows
    .filter((x) => /Списание партий в производство/i.test(x.Оп) && /Расход/i.test(x.Вид))
    .reduce((s, x) => s + upp.parseRu(x.Сумма), 0);
  return {
    period,
    cogs: Math.round(cogs),
    source: 'РегистрНакопления.УчётЗатрат · «Списание партий в производство» (Расход) — материалы в производство',
    refreshedAt: new Date().toISOString()
  };
}

function getGrossProfitCogs(period) {
  const p = period || upp.nowYM();
  return cache.wrap('gp-cogs:' + p, () => computeCogs(p));
}

module.exports = { getGrossProfitCogs };
